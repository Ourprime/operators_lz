n = int(input("Здравствуйте!Введите число и узнайте ,какое количество операций необходимо выполнить, для того, чтобы достичь числа 0, начиная с исходного числа:")) #ввод числа
operacii = 0 #сначала кол-во операций равно 0
while n > 0: #если введенное число больше 0
    if n % 2 == 0: #если число делится на 2 без остатка 
        n=  n//2 #делим на 2
    else: #...то
        n -= 1 #отнимаем по еденице
    operacii += 1 #добавляем к количеству
print(operacii) #вывод числа операций